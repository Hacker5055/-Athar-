    // ── التحويل بين (سورة، آية) والفهرس العالمي ─────────────

    private val OFFSETS: IntArray by lazy {
        val out = IntArray(VERSES_IN_SURAH.size + 1)
        for (i in VERSES_IN_SURAH.indices) out[i + 1] = out[i] + VERSES_IN_SURAH[i]
        out
    }

    /// الفهرس العالمي للآية (١ .. ٦٢٣٦)، أو ٠ إن كانت خارج النطاق.
    ///
    /// ⚠️ صفر لا سالب: «خارج النطاق» قيمة واحدة يمكن للمتصل تجاهلها،
    /// بدل استثناء يوقف قراءة سورة كاملة.
    fun verseId(surah: Int, ayah: Int): Int {
        if (surah !in 1..114) return 0
        val count = VERSES_IN_SURAH[surah - 1]
        if (ayah !in 1..count) return 0
        return OFFSETS[surah - 1] + ayah
    }

    /// عدد آيات السورة، أو ٠ إن كان الرقم خارج النطاق.
    ///
    /// ⚠️ صفر لا استثناء: المتصل يريد أن **يتحقق** من مفتاح قادم من
    /// تخزين قديم، والتحقّق لا يُستثنى منه.
    fun ayahCount(surah: Int): Int =
        if (surah in 1..114) VERSES_IN_SURAH[surah - 1] else 0

    /// عكس verseId — زوج (سورة، آية)، أو (0، 0) خارج النطاق.
    fun surahAyahOf(id: Int): Pair<Int, Int> {
        if (id !in 1..TOTAL_VERSES) return 0 to 0
        var surah = 1
        while (surah < 114 && OFFSETS[surah] < id) surah++
        return surah to (id - OFFSETS[surah - 1])
    }

    // ── الأجزاء والصفحات ────────────────────────────────────

    /// الجزء الذي تقع فيه الآية (١ .. ٣٠).
    ///
    /// ⚠️ **الجزء بنيوي لا حسابي**: يُقرأ من جدول لا يُقسَّم على ٣٠.
    /// فالأجزاء ليست متساوية الآيات، وحدودها معلومة بالنصّ لا بالقسمة —
    /// وأي حساب يعطي حدودًا خاطئة في أجزاء بعينها.
    fun juzOf(surah: Int, ayah: Int): Int = indexIn(JUZ_STARTS, verseId(surah, ayah))

    /// الصفحة التي تقع فيها الآية (١ .. ٦٠٤) برواية حفص.
    fun pageOf(surah: Int, ayah: Int): Int = indexIn(PAGE_STARTS, verseId(surah, ayah))

    /// الصفحة التي تقع فيها الآية — **بالفهرس العالمي**.
    ///
    /// ⚠️ نسخة الفهرسGlobal لا بديل: الحساب في `pageOf` يحتاج
    /// إزاحة السورة، والصفحة تحتاج حسابًا آخر.
    fun pageOfId(id: Int): Int = indexIn(PAGE_STARTS, id)

    /// أول آية في جزء — للانتقال إليه.
    fun startOfJuz(juz: Int): Pair<Int, Int> = startAt(JUZ_STARTS, juz, JUZ_COUNT)

    /// أول آية في صفحة — للانتقال إليها.
    fun startOfPage(page: Int): Pair<Int, Int> = startAt(PAGE_STARTS, page, PAGE_COUNT)

    /// الفهرس العالمي لأول آية في صفحة (١..٦٢٣٦)، أو ٠ خارج النطاق.
    ///
    /// ⚠️ **على مستوى الفهرس العالمي** لا (سورة، آية): صفحة
    /// المصحف تقطع الآيات، فمن يطلب (سورة، آية) يحتاج حساب
    /// إزاحة في كل مرّة.
    fun firstIdOfPage(page: Int): Int =
        if (page in 1..PAGE_COUNT) PAGE_STARTS[page] else 0

    /// الجزء الذي تقع فيه الآية — **بالفهرس العالمي**.
    fun juzOfId(id: Int): Int = indexIn(JUZ_STARTS, id)

    /// الفهرس العالمي لآخر آية في صفحة، أو ٠ خارج النطاق.
    ///
    /// ⚠️ **الحدّ التالي** لا آية بعد الأخيرة: آخر صفحة تنتهي عند
    /// ٦٢٣٦، والحرس في `PAGE_STARTS[605]` هو ٦٢٣٧.
    fun lastIdOfPage(page: Int): Int =
        if (page in 1..PAGE_COUNT) PAGE_STARTS[page + 1] - 1 else 0

    /// الحزب الذي تقع فيه الآية (١ .. ٦٠).
    fun hizbOf(surah: Int, ayah: Int): Int = indexIn(HIZB_STARTS, verseId(surah, ayah))

    /// أول آية في حزب — للانتقال إليه.
    fun startOfHizb(hizb: Int): Pair<Int, Int> = startAt(HIZB_STARTS, hizb, HIZB_COUNT)

    /// الجزء الذي يقع فيه الحزب.
    ///
    /// ⚠️ **حزبان في جزء** لا حساب بالآيات: الحزب ١ والثاني في الجزء
    /// الأول، والثالث والرابع في الثاني.
    fun juzOfHizb(hizb: Int): Int = if (hizb in 1..HIZB_COUNT) (hizb + 1) / 2 else 0

    /// هل الحزب نصفُ جزءٍ ثانٍ (أي يبدأ في منتصف الجزء)؟
    fun isSecondHalf(hizb: Int): Boolean = hizb in 1..HIZB_COUNT && hizb % 2 == 0

    /// ⚠️ **إزاحة القوائم أهمّ ما في هذا الملف**: صفر في أولها وحارس
    /// في آخرها، وبداية الجزء n في `starts[n]` لا `starts[n-1]`. فالجزء
    /// الأول يبدأ عند `starts[1] = 1`، و`starts[0]` ليس بداية شيء.
    /// أخطأتُ فيها أول مرة فصار الجزء الأول فارغًا والثلاثون ناقصًا.
    ///
    /// والبحث خطّي على ≤ ٦٠٤ عنصرًا مرات معدودة في الشاشة، فلا حاجة
    /// لبحث ثنائي يخفي هذه الإزاحة وراء حساب وسط.
    private fun indexIn(starts: IntArray, id: Int): Int {
        if (id == 0) return 0
        for (i in 1 until starts.size - 1) {
            if (id < starts[i + 1]) return i
        }
        return 0
    }

    private fun startAt(starts: IntArray, n: Int, count: Int): Pair<Int, Int> {
        if (n !in 1..count) return 0 to 0
        return surahAyahOf(starts[n])
    }
}
