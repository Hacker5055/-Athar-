package com.athar.athar.adhkar

import com.athar.athar.core.ArabicText

/// ينتقي أقسامًا بعينها من كتاب الأذكار.
///
/// ⚠️ **محض** (بلا `Context`) ليُختبر على JVM: الملف أصل من أصول
/// التطبيق، واختبار الوحدة لا يملك أصولًا.
object AdhkarSections {

    private const val POST_PRAYER = "بعد السلام"

    /// أذكار ما بعد الصلاة.
    ///
    /// ⚠️ المطابقة **بعد التطبيع** لا بالنصّ الحرفي: عناوين الأقسام
    /// مشكولة كاملة («الأَذْكَارُ بَعْدَ السَّلَامِ مِنَ الصَّلَاةِ»)،
    /// فأي مقارنة حرفية تنكسر مع أول اختلاف تشكيل بين إصداري المصدر.
    ///
    /// ⚠️ والعلامة «بعد السلام» لا «بعد» + «سلام»: القسم الذي يسبقه
    /// عنوانه «الدعاء بعد التشهد الأخير **وقبل** السلام»، وهو **داخل**
    /// الصلاة لا بعدها، وقاعدة فضفاضة تطابقه فتأتي أذكار داخل الصلاة
    /// مكان أذكار بعدها. تحقّقتُ من ذلك على الملف الأصلي: شرط فضفاض
    /// يعطي قسمين، وهذا يعطي قسمًا واحدًا.
    fun postPrayer(sections: List<AdhkarSection>): AdhkarSection? =
        sections.firstOrNull { POST_PRAYER in ArabicText.normalize(it.title) }

    /// أذكارُ اليوم: الصباحُ والمساءُ والنوم، والاستخارةُ والسفر.
    ///
    /// ⚠️ **مطابقةٌ تامّةٌ لا جزئية**: العنوانُ مطبوعٌ مشكولًا
    /// («أَذْكَارُ الصَّبَاحِ»)، فالمطابقةُ الجزئيةُ بـ«الصباح»
    /// تطابقُ ما دونه. فالمقارنةُ بعد التطبيع وبالمساواتين.
    ///
    /// ⚠️ والعناوينُ هنا **بلا تشكيل**، والتطبيعُ يزيلُه عن
    /// المصدر ويوحّدُ الألفَ والياءَ والتاءَ المربوطة — فالصباحُ
    /// والمساءُ يُكتبانِ في البيانات «الصَّبَاح» و«المَسَاء».
    private val DAILY = listOf(
        "أذكار الصباح",
        "أذكار المساء",
        "أذكار النوم",
        "دعاء صلاة الاستخارة",
        "دعاء السفر",
    )

    /// الأذكارُ التي يُفتَحُ التطبيقُ من أجلها — بترتيبِ ورودِها.
    ///
    /// ⚠️ وما لا يُوجدُ في المصدر يُسقَط: القائمةُ لا تكسرُ ولا
    /// تُظهرُ عنوانًا فارغًا.
    fun daily(sections: List<AdhkarSection>): List<AdhkarSection> =
        DAILY.mapNotNull { key ->
            val wanted = ArabicText.normalize(key)
            sections.firstOrNull { ArabicText.normalize(it.title) == wanted }
        }
}
